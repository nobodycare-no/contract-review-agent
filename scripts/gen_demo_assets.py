SCAN_LINES = ["技术服务合同（盖章页）", "", "合同编号：HT-2026-0305",
              "甲方：XX科技有限公司（盖章）", "乙方：启明软件有限公司（盖章）",
              "合同金额：人民币 320,000 元整", "签订日期：2026年3月6日"]


def main() -> None:
    import docx

    OUT.mkdir(parents=True, exist_ok=True)
    for name, (title, paras) in DOCX_TEMPLATES.items():
        d = docx.Document()
        d.add_heading(title, level=0)
        for p in paras:
            d.add_paragraph(p)
        d.save(OUT / name)

    (OUT / "数据处理协议.md").write_text(DATA_MD, encoding="utf-8")

    from PIL import Image, ImageDraw, ImageFont

    width, lh = 900, 56
    img = Image.new("RGB", (width, lh * (len(SCAN_LINES) + 2)), "white")
    draw = ImageDraw.Draw(img)
    font = None
    for cand in (r"C:\Windows\Fonts\msyh.ttc", r"C:\Windows\Fonts\simhei.ttf"):
        try:
            font = ImageFont.truetype(cand, 30)
            break
        except OSError:
            continue
    if font is None:
        font = ImageFont.load_default()
    y = lh // 2
    for line in SCAN_LINES:
        draw.text((40, y), line, fill="black", font=font)
        y += lh
    img.save(OUT / "盖章页扫描件.png")

    print("demo assets written:", [p.name for p in sorted(OUT.iterdir())])


if __name__ == "__main__":
    main()
